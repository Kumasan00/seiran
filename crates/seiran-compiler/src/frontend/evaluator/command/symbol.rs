  /// `MathClass` は `Ord` を持たないので、`BTreeMap` のキーにするため序数へ写す
  fn class_ordinal(class: MathClass) -> u8 {
    return match class {
      MathClass::Ord => 0,
      MathClass::Op => 1,
      MathClass::Bin => 2,
      MathClass::Rel => 3,
      MathClass::Open => 4,
      MathClass::Close => 5,
      MathClass::Punct => 6,
    };
  }

  #[test]
