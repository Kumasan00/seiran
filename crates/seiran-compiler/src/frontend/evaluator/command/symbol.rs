/// 記号コマンドが出力する単一文字とその数式クラス
#[derive(Clone, Copy, Debug)]
pub(in crate::frontend::evaluator) struct MathSymbol {
  /// 出力する Unicode 文字
  pub(crate) ch: char,
  /// 数式クラス
  pub(crate) class: MathClass,
}

impl MathSymbol {
  /// 記号エントリを生成する
  const fn new(ch: char, class: MathClass) -> Self { return Self { ch, class }; }
}

